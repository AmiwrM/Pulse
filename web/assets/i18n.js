/* Pulse i18n — Persian (default) and English.
 *
 * The panel was originally written with Persian templates. To avoid keeping
 * two copies of a large UI, English is applied as a DOM translation layer
 * after each render. The dictionary is exact-match and deliberately never
 * touches user data (monitor names, targets, agent names, technical logs).
 */

const PERSIAN_RE = /[\u0600-\u06FF]/;
const STORE_KEY = 'pulse-lang';

export function getLang() {
  return document.documentElement.dataset.lang === 'en' ? 'en' : 'fa';
}

export function setLang(lang) {
  const value = lang === 'en' ? 'en' : 'fa';
  document.documentElement.dataset.lang = value;
  document.documentElement.lang = value;
  document.documentElement.dir = value === 'en' ? 'ltr' : 'rtl';
  try { localStorage.setItem(STORE_KEY, value); } catch { /* private mode */ }
}

export function toggleLang() {
  setLang(getLang() === 'en' ? 'fa' : 'en');
  location.reload();
}

