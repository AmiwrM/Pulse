function faNum(value) {
  return String(value).replace(/[۰-۹]/g, (d) => String('۰۱۲۳۴۵۶۷۸۹'.indexOf(d)));
}

function normalize(text) {
  return String(text).replace(/\u200c/g, ' ').replace(/\s+/g, ' ').trim();
}

const EN_NORM = {};
for (const [key, value] of Object.entries(EN)) EN_NORM[normalize(key)] = value;

function latinize(text) {
  return String(text).replace(/[۰-۹]/g, (d) => String('۰۱۲۳۴۵۶۷۸۹'.indexOf(d)));
}

export function translateText(text) {
  if (getLang() !== 'en') return text;
  const core = normalize(text);
  if (!PERSIAN_RE.test(core)) return text;
  if (Object.prototype.hasOwnProperty.call(EN_NORM, core)) return latinize(EN_NORM[core]);
  for (const [re, replacement] of RULES) {
    if (!re.test(core)) continue;
    return latinize(core.replace(re, replacement));
  }
  return text;
}

const SKIP_SELECTOR = 'script,style,noscript,textarea,pre,code,[data-no-i18n],.mono,.mc-name,.mc-target,.agent-name,.agent-host,.node-name,.record-name,.target,.log-message,.log-time,.version-line .sep';

function skipNode(node) {
  const el = node.nodeType === Node.TEXT_NODE ? node.parentElement : node;
  return !el || !!el.closest(SKIP_SELECTOR);
}

const ATTRS = ['placeholder', 'title', 'aria-label'];

export function translateDOM(root = document.body) {
  if (getLang() !== 'en' || !root) return;
  if (root.nodeType === Node.TEXT_NODE) {
    if (!skipNode(root) && PERSIAN_RE.test(root.nodeValue)) {
      const lead = root.nodeValue.match(/^\s*/)[0];
      const trail = root.nodeValue.match(/\s*$/)[0];
      const core = root.nodeValue.trim();
      const translated = translateText(core);
      if (translated !== core) root.nodeValue = lead + translated + trail;
    }
    return;
  }
  if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_NODE) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      if (!node.nodeValue || !PERSIAN_RE.test(node.nodeValue) || skipNode(node)) return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    },
  });
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const node of nodes) translateDOM(node);
  const elements = root.querySelectorAll ? root.querySelectorAll('*') : [];
  for (const el of elements) {
    if (el.closest(SKIP_SELECTOR)) continue;
    for (const attr of ATTRS) {
      const value = el.getAttribute(attr);
      if (!value || !PERSIAN_RE.test(value)) continue;
      const translated = translateText(value);
      if (translated !== value) el.setAttribute(attr, translated);
    }
  }
}

export function initI18n() {
  let lang = 'fa';
  try { lang = localStorage.getItem(STORE_KEY) === 'en' ? 'en' : 'fa'; } catch { /* ignore */ }
  setLang(lang);
  translateDOM(document.body);
  document.title = translateText(document.title);
  const toggle = document.getElementById('lang-toggle');
  if (toggle) toggle.textContent = lang === 'en' ? 'FA' : 'EN';
  if (lang === 'en') {
    let scheduled = false;
    // Keep a module-level reference: an observer with no retained reference is
    // too easy to lose when the whole app is a single long-lived module.
    domObserver = new MutationObserver((mutations) => {
      if (scheduled || getLang() !== 'en') return;
      scheduled = true;
      setTimeout(() => {
        scheduled = false;
        for (const mutation of mutations) {
          if (mutation.type === 'characterData') translateDOM(mutation.target);
          else if (mutation.type === 'attributes') {
            const el = mutation.target;
            const attr = mutation.attributeName;
            const value = el.getAttribute(attr);
            if (value && PERSIAN_RE.test(value)) {
              const translated = translateText(value);
              if (translated !== value) el.setAttribute(attr, translated);
            }
          } else {
            for (const node of mutation.addedNodes) translateDOM(node);
          }
        }
      }, 0);
    });
    domObserver.observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ATTRS });
  }
}

